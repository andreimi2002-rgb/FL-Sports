import assert from 'node:assert/strict';
import { VIDEO_SOURCES, youtubeId, videoKind, teamAliases, matchRecaps } from '../js/video-data.js';
import { parseFeed, watchMetadata, mergeCatalog, collectCatalog } from '../netlify/lib/video-catalog.mjs';
const source = VIDEO_SOURCES[0], id = 'abcdefghijk', now = Date.parse('2026-11-17T09:00:00Z');
assert.equal(youtubeId('https://youtu.be/' + id), id);
assert.equal(youtubeId('https://www.youtube.com/watch?v=' + id), id);
for (const url of ['http://youtu.be/' + id, 'https://youtube.com.evil.test/watch?v=' + id, 'https://user@youtube.com/watch?v=' + id, 'javascript:alert(1)', 'https://youtu.be/short']) assert.equal(youtubeId(url), null);
assert.equal(videoKind('Heat vs Celtics FULL GAME HIGHLIGHTS', 'nba'), 'recap');
assert.equal(videoKind('Mic’d Up | Inside the locker room', 'nfl'), 'backstage');
assert.ok(teamAliases('Los Angeles Lakers', 'NBA').includes('la lakers'));
const feed = channel => `<feed><yt:channelId>${channel}</yt:channelId><entry><yt:videoId>${id}</yt:videoId><title>Heat &amp; Celtics</title><published>2026-11-17T02:00:00Z</published></entry></feed>`;
assert.equal(parseFeed(feed(source.channel.slice(2)), source)[0].title, 'Heat & Celtics');
assert.throws(() => parseFeed(feed('wrong'), source));
const metadata = `{"channelId":"${source.channel}","lengthSeconds":"725","publishDate":"2026-11-17T02:00:00Z","title":"Heat highlights","isLiveContent":false}`;
assert.equal(watchMetadata(metadata, source).seconds, 725);
assert.throws(() => watchMetadata(metadata.replace(source.channel, 'wrong'), source));
const video = { id, l: 'NBA', source: 'nba', title: 'Miami Heat vs Boston Celtics FULL GAME HIGHLIGHTS November 16, 2026', kind: 'recap', published: '2026-11-17T03:00:00Z', seconds: 725 };
const game = { l: 'NBA', home: 'Miami Heat', away: 'Boston Celtics', date: '2026-11-17T00:30:00Z' };
assert.equal(matchRecaps([video], game)[0].match, 'date');
assert.equal(matchRecaps([video], { ...game, date: '2026-11-16T00:30:00Z' }).length, 0);
assert.equal(matchRecaps([{ ...video, l: 'NFL' }], game).length, 0);
assert.equal(matchRecaps([{ ...video, seconds: 33 }], game).length, 0);
assert.equal(matchRecaps([{ ...video, title: 'Heat vs Celtics FULL GAME HIGHLIGHTS' }], game)[0].match, 'published');
assert.equal(matchRecaps([{ ...video, title: 'Heat vs Celtics FULL GAME HIGHLIGHTS', published: '2026-11-18T03:00:00Z' }], game).length, 0);
const merged = mergeCatalog([video, { ...video, id: 'oldabcdefgh', published: '2026-01-01T00:00:00Z' }], [{ ...video, seconds: null }], now);
assert.equal(merged.length, 1); assert.equal(merged[0].seconds, 725);
const failed = await collectCatalog({ videos: [video] }, { now, metadataLimit: 0, fetcher: async () => { throw Error('offline'); } });
assert.equal(failed.videos.length, 1); assert.equal(failed.sources.filter(s => s.ok).length, 0);
console.log('Video: URL safety, official ownership, RSS, duration, conservative matching and outage retention OK');
