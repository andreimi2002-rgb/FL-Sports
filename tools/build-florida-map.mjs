// One-time static geometry generation. No map SDK, API key or runtime requests.
// us-atlas 3.0.1 redistributes US Census cartographic boundaries.
import { writeFile } from 'node:fs/promises';
const source = 'https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-10m.json';
const response = await fetch(source);
if (!response.ok) throw new Error(`Map source: ${response.status}`);
const topology = await response.json();
const florida = topology.objects.states.geometries.find(g => +g.id === 12);
if (florida?.type !== 'MultiPolygon') throw new Error('Florida geometry missing');
const project = ([lon, lat]) => [(lon + 88.2) * 60, (31.5 - lat) * 68];
const arc = index => {
  let x = 0, y = 0;
  const points = topology.arcs[index < 0 ? ~index : index].map(([dx, dy]) => {
    x += dx; y += dy;
    return project([x * topology.transform.scale[0] + topology.transform.translate[0], y * topology.transform.scale[1] + topology.transform.translate[1]]);
  });
  return index < 0 ? points.reverse() : points;
};
const paths = florida.arcs.flatMap(polygon => polygon.map(ring => {
  const points = ring.flatMap((index, i) => arc(index).slice(i ? 1 : 0));
  return 'M' + points.map(p => p.map(n => n.toFixed(1)).join(',')).join('L') + 'Z';
}));
await writeFile(new URL('../js/florida-map.js', import.meta.url), `// GENERATED by tools/build-florida-map.mjs. US Census geometry via us-atlas 3.0.1.\n// Source: ${source}\nexport const mapPoint = (lon, lat) => [(lon + 88.2) * 60, (31.5 - lat) * 68];\nexport const FLORIDA_PATH = ${JSON.stringify(paths.join(''))};\n`);
console.log(`Florida: ${paths.length} coastlines, ${paths.join('').length} path characters`);
